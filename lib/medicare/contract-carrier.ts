/** Resolve a CMS contract number (e.g. "H5216") to its marketing-brand carrier name. */
export function carrierForContract(contractNumber: string | undefined | null): string {
  if (!contractNumber) return "";
  const c = contractNumber.trim().toUpperCase();
  return CONTRACT_TO_CARRIER[c] ?? "";
}

/** Pull the contract prefix (HXXXX/SXXXX/RXXXX) from a full plan number. */
export function contractFromPlanNumber(planNumber: string): string {
  const m = planNumber.match(/^([HSR]\d{4})/);
  return m ? m[1] : "";
}
